const http = require('http');
const fs = require('fs');
const path = require('path');

const PORT = process.env.PORT || 3000;

const MIME_TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.svg': 'image/svg+xml',
  '.ico': 'image/x-icon'
};

const server = http.createServer((req, res) => {
  const urlPath = req.url.split('?')[0];
  const isRoot = urlPath === '/' || urlPath === '' || urlPath === '/index.html' || urlPath === '/nirapod-jatra' || urlPath === '/nirapod-jatra/';
  let filePath = isRoot ? path.join(__dirname, 'index.html') : path.join(__dirname, path.normalize(urlPath).replace(/^[/\\]+/, ''));
  
  if (fs.existsSync(filePath) && fs.statSync(filePath).isDirectory()) {
    filePath = path.join(filePath, 'index.html');
  }

  fs.stat(filePath, (err, stats) => {
    let statusCode = 200;
    if (err || !stats.isFile()) {
      filePath = path.join(__dirname, '404.html');
      statusCode = 404;
    }

    fs.readFile(filePath, (readErr, content) => {
      if (readErr) {
        res.writeHead(500, { 'Content-Type': 'text/plain' });
        res.end('Internal Server Error');
        return;
      }

      const ext = path.extname(filePath).toLowerCase();
      const contentType = MIME_TYPES[ext] || 'application/octet-stream';

      res.writeHead(statusCode, {
        'Content-Type': contentType,
        'Cache-Control': 'no-cache',
        'Access-Control-Allow-Origin': '*'
      });
      res.end(content);
    });
  });
});

server.listen(PORT, () => {
  console.log(`\n🚀 Nirapod Jatra server is live!`);
  console.log(`🔗 Direct Link: http://localhost:${PORT}\n`);
});
